#!/usr/bin/env bash
# Explicit PB626 ELAN/eMMC policy on the pinned Megi baseline.
# Use the same contract on fresh builds and cached kernel artifacts.
set -Eeuo pipefail
export ARCH=arm CROSS_COMPILE=arm-linux-gnueabihf-

verify_config() {
  local cfg=$1 key
  local required_builtin=(
    USB USB_GADGET USB_MUSB_HDRC USB_MUSB_SUNXI USB_MUSB_GADGET
    NOP_USB_XCEIV PHY_SUN4I_USB EXTCON USB_CONFIGFS USB_CONFIGFS_ACM
    USB_EHCI_HCD USB_EHCI_HCD_PLATFORM USB_OHCI_HCD USB_OHCI_HCD_PLATFORM
    MMC MMC_BLOCK MMC_SUNXI EXT4_FS BLK_DEV_INITRD RD_GZIP ARM_APPENDED_DTB AUTO_ZRELADDR
    CONFIGFS_FS DEVTMPFS DEVTMPFS_MOUNT UEVENT_HELPER
    REGULATOR_TPS65185 PWM_SUN4I BACKLIGHT_PWM FB_SUN5I_EINK
    MEDIA_SUPPORT MEDIA_SUPPORT_FILTER MEDIA_PLATFORM_SUPPORT VIDEO_DEV VIDEOBUF2_CORE VIDEOBUF2_V4L2 VIDEOBUF2_MEMOPS VIDEOBUF2_DMA_CONTIG
    CMA DMA_CMA COMPACTION CPU_FREQ_DEFAULT_GOV_ONDEMAND TOUCHSCREEN_ELAN
    MFD_AXP20X_I2C REGULATOR_AXP20X AXP20X_ADC IIO BATTERY_AXP20X CHARGER_AXP20X
    RTC_DRV_PCF8563 KEYBOARD_GPIO KEYBOARD_SUN4I_LRADC INPUT_AXP20X_PEK INPUT_EVDEV
    PM PM_SLEEP SUSPEND SUSPEND_FREEZER PM_DEBUG PM_SLEEP_DEBUG THERMAL CPU_THERMAL SUNXI_WATCHDOG
    CPU_IDLE CPU_IDLE_GOV_MENU ARM_CPUIDLE
    VT UNIX98_PTYS SYSVIPC POSIX_MQUEUE FUTEX EPOLL SIGNALFD TIMERFD EVENTFD
    INOTIFY_USER SHMEM TMPFS PROC_FS SYSFS MULTIUSER SECCOMP SECCOMP_FILTER
    FHANDLE TMPFS_XATTR TMPFS_POSIX_ACL EXT4_FS_POSIX_ACL AUTOFS_FS
    KEYS KEY_DH_OPERATIONS CRYPTO_USER_API_HASH CRYPTO_USER_API_SKCIPHER
    CRYPTO_AES CRYPTO_ECB CRYPTO_CBC CRYPTO_CMAC CRYPTO_HMAC
    CRYPTO_MD5 CRYPTO_SHA1 CRYPTO_SHA256 CRYPTO_SHA512 CRYPTO_DES
    CRYPTO_RSA ASYMMETRIC_KEY_TYPE ASYMMETRIC_PUBLIC_KEY_SUBTYPE X509_CERTIFICATE_PARSER PKCS8_PRIVATE_KEY_PARSER
    POSIX_TIMERS KCMP
    UNIX INET IPV6 PACKET NET_NS USER_NS IP_MULTIPLE_TABLES IPV6_MULTIPLE_TABLES
    CFG80211 MAC80211 NETFILTER NF_TABLES_INET NF_TABLES_IPV4 NF_TABLES_IPV6
    CGROUPS MEMCG CGROUP_PIDS BLK_CGROUP BLK_DEV_THROTTLING CGROUP_SCHED FAIR_GROUP_SCHED
    NAMESPACES PSI LRU_GEN LRU_GEN_ENABLED
    SWAP ZRAM ZRAM_BACKEND_LZ4 ZRAM_DEF_COMP_LZ4
    EXPERT BASE_SMALL CC_OPTIMIZE_FOR_SIZE HZ_100 NO_HZ_IDLE HIGH_RES_TIMERS
    DEBUG_FS KALLSYMS STACKPROTECTOR STACKPROTECTOR_STRONG
  )
  local required_module=(
    RTL8XXXU DRM DRM_LIMA
    NF_TABLES NF_CONNTRACK NFT_CT NFT_REJECT NFT_REJECT_INET NFT_NAT NFT_MASQ
    NFT_REDIR NFT_LOG NFT_LIMIT NF_NAT WIREGUARD TUN
    XFRM_USER INET_ESP INET6_ESP
    FUSE_FS BLK_DEV_LOOP VFAT_FS EXFAT_FS MTD MTD_SPI_NOR SPI_SUN4I
  )
  local forbidden=(
    ARM_ATAG_DTB_COMPAT USB_MUSB_DUAL_ROLE USB_MUSB_HOST USB_OTG USB_OTG_FSM
    USB_CONFIGFS_SERIAL USB_CONFIGFS_OBEX USB_CONFIGFS_NCM USB_CONFIGFS_ECM
    USB_CONFIGFS_ECM_SUBSET USB_CONFIGFS_RNDIS USB_CONFIGFS_EEM
    USB_CONFIGFS_MASS_STORAGE USB_CONFIGFS_F_LB_SS USB_CONFIGFS_F_FS
    USB_CONFIGFS_F_HID USB_CONFIGFS_F_PRINTER USB_CDC_COMPOSITE USB_WDM
    USB_STORAGE SCSI BLK_DEV_SD
    TOUCHSCREEN_CYTTSP4 TOUCHSCREEN_EDT_FT5X06 BMA180 LTR501 AK8975
    KEYBOARD_GPIO_POLLED SUNXI_RSB MFD_SUN6I_PRCM ARM_CCI_PMU SENSORS_NTC_THERMISTOR
    DRM_SUN4I DRM_FBDEV_EMULATION FB FRAMEBUFFER_CONSOLE
    F2FS_FS FS_ENCRYPTION CUSE BLK_DEV_NBD BLK_DEV_INTEGRITY
    SPI_SPIDEV MTD_BLOCK_RO
    IP_SET NF_FLOW_TABLE MPTCP NETFILTER_XTABLES NETFILTER_NETLINK_QUEUE
    NF_CONNTRACK_FTP NF_CONNTRACK_H323 NF_CONNTRACK_IRC NF_CONNTRACK_NETBIOS_NS
    NF_CONNTRACK_SNMP NF_CONNTRACK_PPTP NF_CONNTRACK_SIP NF_CONNTRACK_TFTP
    NFT_QUEUE NFT_OSF NFT_TUNNEL NFT_DUP_NETDEV NFT_FWD_NETDEV
    BPF_SYSCALL CGROUP_BPF CGROUP_DEVICE RT_GROUP_SCHED SCHED_AUTOGROUP BLK_CGROUP_IOLATENCY
    BSD_PROCESS_ACCT TASK_DELAY_ACCT TASK_XACCT
    MEDIA_CAMERA_SUPPORT MEDIA_ANALOG_TV_SUPPORT MEDIA_DIGITAL_TV_SUPPORT
    MEDIA_RADIO_SUPPORT MEDIA_SDR_SUPPORT MEDIA_TEST_SUPPORT MEDIA_SUBDRV_AUTOSELECT
    DVB_CORE MEDIA_TUNER MEDIA_ATTACH CXD2880_SPI_DRV
    SLUB_TINY ZRAM_WRITEBACK ZRAM_MEMORY_TRACKING ZRAM_TRACK_ENTRY_ACTIME ZRAM_MULTI_COMP ZSWAP
    HZ_PERIODIC HZ_1000 MODULE_FORCE_LOAD IIO_CONFIGFS SUN5I_PM HIBERNATION
  )
  for key in "${required_builtin[@]}"; do
    grep -qx "CONFIG_$key=y" "$cfg" || { echo "REQUIRED BUILT-IN MISSING: CONFIG_$key=y" >&2; return 1; }
  done
  for key in "${required_module[@]}"; do
    grep -qx "CONFIG_$key=m" "$cfg" || { echo "REQUIRED MODULE MISSING: CONFIG_$key=m" >&2; return 1; }
  done
  for key in "${forbidden[@]}"; do
    if grep -Eq "^CONFIG_$key=(y|m)$" "$cfg"; then
      echo "UNEXPECTED ENABLED OPTION: CONFIG_$key" >&2
      return 1
    fi
  done
  if grep -E '^CONFIG_(DVB_|MEDIA_TUNER_)[A-Za-z0-9_]+=(y|m)$' "$cfg"; then
    echo 'UNEXPECTED television frontend or tuner in resolved config' >&2
    return 1
  fi
  grep -qx 'CONFIG_CMA_SIZE_MBYTES=32' "$cfg"
  grep -qx 'CONFIG_HZ=100' "$cfg"
  grep -qx 'CONFIG_UEVENT_HELPER_PATH=""' "$cfg"
  grep -qx 'CONFIG_ZRAM_DEF_COMP="lz4"' "$cfg"
  echo 'PB626 ELAN/eMMC kernel policy verified.'
}

if [[ ${1:-} == --check ]]; then
  verify_config "${2:?path to resolved kernel .config}"
  exit
fi

make -C linux pocketbook_touch_lux_3_defconfig
c=linux/scripts/config
"$c" --file linux/.config \
  -e USB -e NOP_USB_XCEIV -e EXTCON -e PHY_SUN4I_USB \
  -e USB_MUSB_HDRC -e USB_MUSB_SUNXI -d USB_MUSB_DUAL_ROLE -d USB_MUSB_HOST -e USB_MUSB_GADGET \
  -d USB_OTG -d USB_OTG_FSM \
  -e USB_GADGET -e USB_LIBCOMPOSITE -e USB_CONFIGFS -e USB_CONFIGFS_ACM \
  -d USB_CONFIGFS_SERIAL -d USB_CONFIGFS_OBEX -d USB_CONFIGFS_NCM -d USB_CONFIGFS_ECM \
  -d USB_CONFIGFS_ECM_SUBSET -d USB_CONFIGFS_RNDIS -d USB_CONFIGFS_EEM -d USB_CONFIGFS_MASS_STORAGE \
  -d USB_CONFIGFS_F_LB_SS -d USB_CONFIGFS_F_FS -d USB_CONFIGFS_F_HID -d USB_CONFIGFS_F_PRINTER \
  -d USB_CDC_COMPOSITE -d USB_WDM -d USB_STORAGE \
  -e USB_EHCI_HCD -e USB_EHCI_HCD_PLATFORM -e USB_OHCI_HCD -e USB_OHCI_HCD_PLATFORM \
  -e MMC -e MMC_BLOCK -e MMC_SUNXI -e EXT4_FS -m VFAT_FS -m EXFAT_FS \
  -e ARM_APPENDED_DTB -e AUTO_ZRELADDR -d ARM_ATAG_DTB_COMPAT \
  -e BLK_DEV_INITRD -e RD_GZIP -e DEVTMPFS -e DEVTMPFS_MOUNT -e CONFIGFS_FS -e UEVENT_HELPER \
  -d REGULATOR_TP65185X -e REGULATOR_TPS65185 -e BACKLIGHT_PWM \
  -e MEDIA_SUPPORT -e MEDIA_SUPPORT_FILTER -e MEDIA_PLATFORM_SUPPORT -e VIDEO_DEV -e FB_SUN5I_EINK \
  -d MEDIA_CAMERA_SUPPORT -d MEDIA_ANALOG_TV_SUPPORT -d MEDIA_DIGITAL_TV_SUPPORT \
  -d MEDIA_RADIO_SUPPORT -d MEDIA_SDR_SUPPORT -d MEDIA_TEST_SUPPORT -d MEDIA_SUBDRV_AUTOSELECT \
  -d DVB_CORE -d MEDIA_TUNER -d CXD2880_SPI_DRV \
  -d TOUCHSCREEN_CYTTSP4 -d TOUCHSCREEN_CYTTSP4_CORE -d TOUCHSCREEN_CYTTSP4_I2C \
  -e TOUCHSCREEN_ELAN -d TOUCHSCREEN_EDT_FT5X06 \
  -d BMA180 -d LTR501 -d AK8975 -d KEYBOARD_GPIO_POLLED -d SUNXI_RSB \
  -d MFD_SUN6I_PRCM -d ARM_CCI_PMU -d SENSORS_NTC_THERMISTOR \
  -d CPU_FREQ_DEFAULT_GOV_PERFORMANCE -e CPU_FREQ_DEFAULT_GOV_ONDEMAND \
  -m DRM -m DRM_LIMA -d DRM_SUN4I -d DRM_FBDEV_EMULATION -d FB -d FRAMEBUFFER_CONSOLE \
  -m RTL8XXXU -e RFKILL \
  -d F2FS_FS -d FS_ENCRYPTION -d CUSE -e AUTOFS_FS -m FUSE_FS \
  -m BLK_DEV_LOOP -d BLK_DEV_NBD -d BLK_DEV_INTEGRITY -d SCSI -d BLK_DEV_SD \
  -m MTD -m MTD_SPI_NOR -m SPI_SUN4I -d MTD_BLOCK_RO -d SPI_SPIDEV \
  -d IIO_CONFIGFS -d MODULE_FORCE_LOAD \
  --set-str LOCALVERSION '-pb626-eink-builtin-mbusfix-lean'

# IPv4/IPv6 nftables, stateful firewall and VPN routing. No legacy xtables,
# IP sets, protocol-specific NAT helpers or forwarding offload.
"$c" --file linux/.config \
  -e IP_ADVANCED_ROUTER -e IP_MULTIPLE_TABLES -e IPV6_MULTIPLE_TABLES \
  -e NETFILTER -e NETFILTER_ADVANCED -m NF_TABLES -e NF_TABLES_INET \
  -e NF_TABLES_IPV4 -e NF_TABLES_IPV6 -m NF_CONNTRACK -m NF_NAT \
  -m NFT_CT -m NFT_REJECT -m NFT_REJECT_INET -m NFT_NAT -m NFT_MASQ \
  -m NFT_REDIR -m NFT_LOG -m NFT_LIMIT -m NFT_FIB_IPV4 -m NFT_FIB_IPV6 -m NFT_FIB_INET \
  -d NETFILTER_XTABLES -d IP_SET -d NF_FLOW_TABLE -d NF_FLOW_TABLE_INET -d MPTCP \
  -d NF_CONNTRACK_FTP -d NF_CONNTRACK_H323 -d NF_CONNTRACK_IRC -d NF_CONNTRACK_NETBIOS_NS \
  -d NF_CONNTRACK_SNMP -d NF_CONNTRACK_PPTP -d NF_CONNTRACK_SIP -d NF_CONNTRACK_TFTP \
  -d NETFILTER_NETLINK_QUEUE -d NETFILTER_NETLINK_OSF -d NFT_QUEUE -d NFT_OSF \
  -d NFT_TUNNEL -d NFT_DUP_NETDEV -d NFT_FWD_NETDEV \
  -m WIREGUARD -m TUN -m XFRM_USER -m INET_ESP -m INET6_ESP -d XFRM_SUB_POLICY

# Low-memory policy: keep the standard Linux ABI and cgroup v2 controllers
# for memory/PIDs/CPU/IO; retain namespaces for sandboxing. No eBPF userspace
# VM/cgroup attachment or legacy device/RT controllers in this profile.
"$c" --file linux/.config \
  -e EXPERT -e BASE_SMALL -d CC_OPTIMIZE_FOR_PERFORMANCE -e CC_OPTIMIZE_FOR_SIZE \
  -d SLUB_TINY -e STACKPROTECTOR -e STACKPROTECTOR_STRONG \
  -e CGROUPS -e MEMCG -e CGROUP_PIDS -e CGROUP_SCHED -e FAIR_GROUP_SCHED \
  -e BLK_CGROUP -e BLK_DEV_THROTTLING -d BLK_CGROUP_IOLATENCY \
  -d BPF_SYSCALL -d CGROUP_BPF -d CGROUP_DEVICE -d RT_GROUP_SCHED -d SCHED_AUTOGROUP \
  -e NAMESPACES -e USER_NS -e NET_NS -e PSI -d PSI_DEFAULT_DISABLED \
  -e LRU_GEN -e LRU_GEN_ENABLED \
  -d BSD_PROCESS_ACCT -d TASK_DELAY_ACCT -d TASK_XACCT \
  -e DEBUG_FS -e KALLSYMS \
  -d HZ_1000 -e HZ_100 -d HZ_PERIODIC -e NO_HZ_IDLE -e HIGH_RES_TIMERS \
  -e SWAP -e ZRAM -e ZRAM_BACKEND_LZ4 -d ZRAM_BACKEND_LZO \
  -d ZRAM_DEF_COMP_LZORLE -e ZRAM_DEF_COMP_LZ4 \
  -d ZRAM_WRITEBACK -d ZRAM_MEMORY_TRACKING -d ZRAM_TRACK_ENTRY_ACTIME -d ZRAM_MULTI_COMP -d ZSWAP \
  -e CMA -e DMA_CMA -e COMPACTION --set-val CMA_SIZE_MBYTES 32
# Debian 13 systemd/udev and iwd ABI. Retain the empty legacy hotplug
# helper for the independent RAM recovery, never configure a boot-time path.
"$c" --file linux/.config \
  -e FHANDLE -e TMPFS_XATTR -e TMPFS_POSIX_ACL -e EXT4_FS_POSIX_ACL -e AUTOFS_FS \
  --set-str UEVENT_HELPER_PATH '' \
  -e KEYS -e KEY_DH_OPERATIONS -e CRYPTO_USER_API_HASH -e CRYPTO_USER_API_SKCIPHER \
  -e CRYPTO_AES -e CRYPTO_ECB -e CRYPTO_CBC -e CRYPTO_CMAC -e CRYPTO_HMAC \
  -e CRYPTO_MD5 -e CRYPTO_SHA1 -e CRYPTO_SHA256 -e CRYPTO_SHA512 -e CRYPTO_DES \
  -e CRYPTO_RSA -e ASYMMETRIC_KEY_TYPE -e ASYMMETRIC_PUBLIC_KEY_SUBTYPE -e X509_CERTIFICATE_PARSER -e PKCS8_PRIVATE_KEY_PARSER \
  -e POSIX_TIMERS -e KCMP -d FW_LOADER_USER_HELPER
# The verified cold-boot SPL has no Megi RTC/DRAM resume contract yet.
"$c" --file linux/.config -e SUSPEND -e PM_DEBUG -e PM_SLEEP_DEBUG \
  -e CPU_IDLE -e CPU_IDLE_GOV_MENU -e ARM_CPUIDLE -d SUN5I_PM -d HIBERNATION
# The DT pool has priority over Kconfig; common.fragment sets the same 32 MiB.
make -C linux olddefconfig
verify_config linux/.config
